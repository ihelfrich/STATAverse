if (import.meta.url === `file://${process.argv[1]}`) {
  const folder = await fs.mkdtemp(
    path.join(os.tmpdir(), "stataverse-expressions-native-"),
  );
  const audit = [
    "version 17",
    "set processors 1",
    "set more off",
    "clear",
    'file open out using "scalar.tsv", write text replace',
  ];
  // A failed file write leaves part of its line behind, so each expression
  // goes into a scalar first and is written only once its type is known.
  SCALAR.forEach((e, k) =>
    audit.push(
      "capture scalar drop __v",
      `capture scalar __v = ${e}`,
      "local rc = _rc",
      "if `rc' {",
      `file write out "${k}" _tab "E" _tab "\`rc'" _n`,
      "}",
      "else {",
      "capture scalar __t = scalar(__v) - 1",
      "if _rc {",
      `file write out "${k}" _tab "S" _tab "[" (scalar(__v)) "]" _n`,
      "}",
      "else {",
      `file write out "${k}" _tab "N" _tab (string(scalar(__v), "%21x")) _n`,
      "}",
      "}",
    ),
  );
  audit.push(
    "file close out",
    "clear",
    "set obs 6",
    ...DATA_VARIABLES.flatMap(([name, type, values]) =>
      type === "str"
        ? [
            `generate str1 ${name} = ""`,
            ...values.map((v, i) => `replace ${name} = "${v}" in ${i + 1}`),
          ]
        : [
            `generate ${type} ${name} = .`,
            ...values.map((v, i) => `replace ${name} = ${v} in ${i + 1}`),
          ],
    ),
    "scalar k = 3",
    'scalar ks = "txt"',
    'file open out using "data.tsv", write text replace',
  );
  const dataCases = [
    ...DATA.map((e) => ({ expression: e, by: false })),
    ...BY.map((e) => ({ expression: e, by: true })),
  ];
  dataCases.forEach(({ expression, by }, k) => {
    const prefix = by ? "bysort g (id): " : "";
    audit.push(
      "capture drop r",
      "quietly summarize price",
      `capture ${prefix}generate r = ${expression}`,
      "local rc = _rc",
      `file write out "${k}" _tab "rc" _tab "\`rc'" _n`,
      "if !`rc' {",
      "local t : type r",
      `file write out "${k}" _tab "type" _tab "\`t'" _n`,
      'if substr("`t\'", 1, 3) == "str" {',
      "forvalues j = 1/6 {",
      `file write out "${k}" _tab "val" _tab "[" (r[\`j']) "]" _n`,
      "}",
      "}",
      "else {",
      "drop r",
      "quietly summarize price",
      `${prefix}generate double r = ${expression}`,
      "forvalues j = 1/6 {",
      `file write out "${k}" _tab "val" _tab (string(r[\`j'], "%21x")) _n`,
      "}",
      "}",
      "}",
    );
  });
  audit.push("file close out", "exit, clear", "");
  await fs.writeFile(path.join(folder, "audit.do"), audit.join("\n"));
  await promisify(execFile)(
    "/Applications/Stata/StataMP.app/Contents/MacOS/stata-mp",
    ["-b", "do", "audit.do"],
    { cwd: folder, timeout: 120000 },
  );
  const read = async (name) =>
    (await fs.readFile(path.join(folder, name), "utf8"))
      .split("\n")
      .filter(Boolean)
      .map((line) => line.split("\t"));
  const scalar = SCALAR.map((expression) => ({ expression }));
  for (const [k, kind, ...rest] of await read("scalar.tsv")) {
    const text = rest.join("\t");
    if (kind === "E") scalar[k].rc = Number(text);
    else if (kind === "S") scalar[k].string = text.slice(1, -1);
    else scalar[k].number = hexToDouble(text);
  }
  const missingScalar = scalar.filter((c) => Object.keys(c).length < 2);
  if (missingScalar.length)
    throw new Error(
      `Stata did not report ${missingScalar.length} scalar cases, first: ${missingScalar[0].expression}. See ${folder}/audit.log`,
    );
  const data = dataCases.map((c) => ({ ...c, rc: null, values: [] }));
  for (const [k, kind, ...rest] of await read("data.tsv")) {
    const c = data[k],
      text = rest.join("\t");
    if (kind === "rc") c.rc = Number(text);
    else if (kind === "type") c.type = text;
    else
      c.values.push(
        c.type.startsWith("str") ? text.slice(1, -1) : hexToDouble(text),
      );
  }
  const short = data.filter(
    (c) => c.rc === null || (!c.rc && c.values.length !== 6),
  );
  if (short.length)
    throw new Error(
      `Stata did not finish ${short.length} data cases, first: ${short[0].expression}. See ${folder}/audit.log`,
    );
  await fs.writeFile(
    "tests/fixtures/stata-runtime-expressions.json",
    await format(
      JSON.stringify({
        source:
          "Recorded from installed Stata by tools/check-expressions-native.mjs under version 17. Numeric results were written with %21x and are exact doubles; data cases are generate r = EXP after summarize price, with scalars k = 3 and ks = txt.",
        variables: DATA_VARIABLES,
        scalar,
        data,
      }),
      { parser: "json" },
    ),
  );
  console.log(
    `Recorded ${scalar.length} scalar and ${data.length} data expressions from installed Stata.`,
  );
  await fs.rm(folder, { recursive: true, force: true });
}
