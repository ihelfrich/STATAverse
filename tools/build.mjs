// The landing page shows three fixed worked examples. Compute their exact
// results here; students load the full command engine only in Practice.
const previewSession = new PracticeSession();
const examples = {};
for (const [id, command] of Object.entries({
  scatter: "scatter score hours",
  summarize: "summarize hours score",
  regress: "regress score hours",
})) {
  previewSession.load("study");
  const result = previewSession.run(command).at(-1);
  examples[id] =
    id === "scatter"
      ? { graph: { points: result.graph.points } }
      : id === "summarize"
        ? { stats: result.stats }
        : {
            model: {
              n: result.model.n,
              r2: result.model.r2,
              coefficients: result.model.coefficients,
            },
          };
}
